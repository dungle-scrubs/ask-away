def panel(scene: Image.Image, source: Path, xy: tuple[int, int], scale: float) -> None:
    with Image.open(source) as capture:
        asset = capture.convert("RGBA")
        asset = asset.resize(
            (round(asset.width * scale * RENDER), round(asset.height * scale * RENDER)),
            Image.Resampling.LANCZOS,
        )
        scene.alpha_composite(asset, box(xy))


def cursor(scene: Image.Image, xy: tuple[int, int]) -> None:
    x, y = xy
    points = [(0, 0), (0, 29), (7, 22), (13, 35), (19, 32), (13, 20), (24, 20)]
    draw = ImageDraw.Draw(scene)
    draw.polygon(
        [box((x + dx + 2, y + dy + 2)) for dx, dy in points], fill=(0, 0, 0, 130)
    )
    points = [box((x + dx, y + dy)) for dx, dy in points]
    draw.polygon(points, fill="#11151c")
    draw.line(points + [points[0]], fill="#eaf0f6", width=2 * RENDER, joint="curve")


def main() -> None:
    inputs = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/shots")
    output = ROOT / "docs"
    output.mkdir(exist_ok=True)
    base = desktop()
    hero = base.copy()
    panel(hero, inputs / "panel-hero.png", (600, 251), 0.8)
    cursor(hero, (1293, 722))
    batch = base.copy()
    panel(batch, inputs / "panel-batch.png", (215, 403), 1.0)
    cascade = base.copy()
    for index in range(3):
        panel(
            cascade,
            inputs / f"panel-cas{index + 1}.png",
            (490 + index * 48, 302 + index * 48),
            1.0,
        )
    for name, scene in (("panel", hero), ("batch", batch), ("cascade", cascade)):
        scene.convert("RGB").resize(SIZE, Image.Resampling.LANCZOS).save(
            output / f"{name}.png"
        )


if __name__ == "__main__":
    main()

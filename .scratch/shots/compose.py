"""Draw README desktops from synthetic chrome and untouched panel captures.

Run with Pillow installed: python compose.py [capture-directory].
The default inputs are /tmp/shots. All coordinates below are final PNG pixels;
the canvas is drawn at twice that resolution, then downsampled once.
Only supplied panel PNGs are read as image assets. Keep those source captures
with this script when archiving the task; they are not generated by this file.
"""

import math
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
SIZE = (1600, 1000)
RENDER = 2
MONO = (
    "/System/Library/Fonts/Menlo.ttc",
    "/System/Library/Fonts/Supplemental/Courier New.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
)
UI = (
    "/System/Library/Fonts/SFNS.ttf",
    "/System/Library/Fonts/Helvetica.ttc",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
)


def font(size: int, mono: bool = False) -> ImageFont.FreeTypeFont:
    for path in MONO if mono else UI:
        if Path(path).is_file():
            return ImageFont.truetype(path, size * RENDER, index=0)
    raise FileNotFoundError("No suitable UI or monospace font installed")


def box(bounds: tuple[float, ...]) -> tuple[int, ...]:
    return tuple(round(value * RENDER) for value in bounds)


def text(
    draw: ImageDraw.ImageDraw,
    xy: tuple[float, float],
    value: str,
    color: str = "#a3adb9",
    size: int = 18,
    mono: bool = False,
) -> None:
    draw.text(box(xy), value, font=font(size, mono), fill=color)


def wallpaper() -> Image.Image:
    small = Image.new("RGB", (400, 250))
    pixels = small.load()
    for y in range(250):
        for x in range(400):
            glow = math.exp(-(((x - 266) / 142) ** 2 + ((y - 130) / 105) ** 2))
            pixels[x, y] = (
                round(8 + 2 * glow),
                round(12 + 10 * glow + 2 * y / 250),
                round(21 + 13 * glow + 3 * y / 250),
            )
    return small.resize(box(SIZE), Image.Resampling.BICUBIC).convert("RGBA")


def window(
    scene: Image.Image, bounds: tuple[int, int, int, int], title: str
) -> ImageDraw.ImageDraw:
    x, y, w, h = bounds
    shadow = Image.new("RGBA", scene.size)
    ImageDraw.Draw(shadow).rounded_rectangle(
        box((x, y + 12, x + w, y + h + 12)), radius=18 * RENDER, fill=(0, 0, 0, 150)
    )
    scene.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(22 * RENDER)))
    draw = ImageDraw.Draw(scene)
    draw.rounded_rectangle(
        box((x, y, x + w, y + h)),
        radius=12 * RENDER,
        fill="#151a23",
        outline="#343b47",
        width=RENDER,
    )
    draw.rounded_rectangle(
        box((x + 1, y + 1, x + w - 1, y + 43)),
        radius=11 * RENDER,
        fill="#242a35",
    )
    draw.rectangle(box((x + 1, y + 23, x + w - 1, y + 43)), fill="#242a35")
    for i, color in enumerate(("#df6a65", "#d8b65c", "#6ab880")):
        cx = x + 23 + i * 22
        draw.ellipse(box((cx - 6, y + 16, cx + 6, y + 28)), fill=color)
    title_font = font(16)
    width = draw.textlength(title, font=title_font) / RENDER
    text(draw, (x + (w - width) / 2, y + 12), title, "#b2bac6", 16)
    return draw


